// Exports the ABIs the engine and app need from Foundry's build output into packages/shared.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts/out");
const names = {
  ClutchHook: "ClutchHook.sol/ClutchHook.json",
  ClutchRouter: "ClutchRouter.sol/ClutchRouter.json",
  HumanPassGate: "HumanPassGate.sol/HumanPassGate.json",
  LPVault: "LPVault.sol/LPVault.json",
  SequencerGuard: "SequencerGuard.sol/SequencerGuard.json",
  BlackoutGuardHook: "BlackoutGuardHook.sol/BlackoutGuardHook.json",
  MockSequencerFeed: "MockSequencerFeed.sol/MockSequencerFeed.json",
  MockUSDC: "Tokens.sol/MockUSDC.json",
  StreamToken: "Tokens.sol/StreamToken.json",
  PoolManager: "PoolManager.sol/PoolManager.json",
};
const withBytecode = ["StreamToken"];
let src = "// Generated by scripts/export-abis.mjs from contracts/out. Do not edit.\n\n";
for (const [name, file] of Object.entries(names)) {
  const { abi, bytecode } = JSON.parse(readFileSync(join(out, file), "utf8"));
  src += `export const ${name}Abi = ${JSON.stringify(abi)} as const;\n\n`;
  if (withBytecode.includes(name)) src += `export const ${name}Bytecode = ${JSON.stringify(bytecode.object)} as \`0x\${string}\`;\n\n`;
}
writeFileSync(join(root, "packages/shared/src/abis.ts"), src);
console.log("wrote packages/shared/src/abis.ts");
